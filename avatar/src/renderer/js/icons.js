/**
 * Render ikon SVG Lucide (outline) secara konsisten.
 * @param {string} name - nama ikon Lucide (house, mic, brain, ...).
 * @param {object} [opts] - { size = 20, strokeWidth = 1.8, className = '' }.
 * @returns {string} markup SVG (aman untuk innerHTML).
 */
export function renderIcon(name, opts = {}) {
  const size = opts.size ?? 20
  const strokeWidth = opts.strokeWidth ?? 1.8
  const cls = opts.className ?? ''
  const inner = ICONS[name] || ICONS['circle-alert'] // fallback: circle-alert

  return `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`
}

/**
 * Cek apakah nama ikon tersedia (untuk validasi fallback).
 */
export function hasIcon(name) {
  return Boolean(ICONS[name])
}
